import { useEffect, useId, useState } from "react";
import { ShellDialog } from "./shell-dialog";
import { ApiError } from "./cc-client";
import { loadContextRuns, loadRecordedContext, type ContextRun, type RecordedContext } from "./sane-context-client";
import type { Config } from "./types";
import "./sane-context.css";

type Load<T> = { kind: "loading" } | { kind: "error"; message: string } | { kind: "ready"; value: T };
function message(error: unknown): string {
  if (error instanceof ApiError && error.status === 401) return "Sign-in expired. Reconnect or sign in again to inspect recorded context.";
  if (error instanceof ApiError && error.status === 403) return "Access to this recorded context is unavailable.";
  if (error instanceof ApiError && error.status === 409) return "Protected run evidence is unavailable or could not be read intact. The journal may be incomplete, changed, or torn. Nothing was repaired and no current context or legacy history was substituted.";
  if (error instanceof ApiError && [404, 410].includes(error.status)) return "Recorded run evidence is unavailable. The run may be missing, retired, or unsupported by this bridge.";
  return error instanceof Error ? error.message : "Recorded SANE context is unavailable.";
}

function RunContext({ run }: { run: ContextRun }) {
  const [state, setState] = useState<Load<RecordedContext[]>>({ kind: "loading" });
  const [attempt, setAttempt] = useState(0);
  const [selected, setSelected] = useState(0);
  const id = useId();
  useEffect(() => {
    let current = true;
    const controller = new AbortController(), signal = AbortSignal.any([controller.signal, AbortSignal.timeout(25_000)]);
    setState({ kind: "loading" });
    void loadRecordedContext(run, signal).then(value => {
      if (current) { setSelected(0); setState({ kind: "ready", value }); }
    }).catch(error => { if (current) setState({ kind: "error", message: message(error) }); });
    return () => { current = false; controller.abort(); };
  }, [run, attempt]);
  if (state.kind === "loading") return <p role="status">Loading recorded outgoing messages…</p>;
  if (state.kind === "error") return <div role="alert"><p className="notice error">{state.message}</p><button type="button" className="text-button" onClick={() => setAttempt(value => value + 1)}>Retry</button></div>;
  const entry = state.value[selected];
  if (!entry) return <div><p role="status">No structured SANE context submission was recorded for this run. Older or imported history may not retain this evidence; prepared snapshots and current files are not substitutes.</p><button type="button" className="text-button" onClick={() => setAttempt(value => value + 1)}>Refresh</button></div>;
  return <>
    <label htmlFor={id}>Recorded message</label>
    <select id={id} value={selected} onChange={event => setSelected(Number(event.target.value))}>{state.value.map((item, index) => <option key={item.sequence} value={index}>{item.placement ?? "Unchecked composition"} · {item.messageId}</option>)}</select>
    <dl className="facts">
      {[["Run ID", run.id], ["Message ID", entry.messageId], ["Journal sequence", String(entry.sequence)], ["Recorded at", entry.time],
        ["Recorded placement", entry.placement ?? "Unavailable"], ["Recorded origin", entry.origin ?? "Unavailable"],
        ["Recorded submission", entry.submission], ["Recorded native acceptance", entry.acceptance], ["Transport SHA-256", entry.sha256 ?? "Unavailable"]].map(([label, value]) => <div key={label}><dt>{label}</dt><dd>{value}</dd></div>)}
    </dl>
    <p className="muted">A submission record alone does not prove delivery. Claude Code pipe flush is submitted with acceptance unknown, not accepted. Even recorded native acceptance does not prove model consumption or current activation.</p>
    {entry.warning && <p className="notice" role="status">{entry.warning}</p>}
    {entry.segments && <details><summary>Selected context · {entry.segments.length}</summary><ul>{entry.segments.map(segment => <li key={segment.id}><strong>{segment.id}</strong> · {segment.category}<p>{segment.reason}</p></li>)}</ul></details>}
    {entry.authoredBody !== undefined && <details><summary>Authored body · recorded byte range</summary><p className="muted">Range and SHA-256 checked against the saved transport, not reconstructed from current sources. “Authored body” is the composer’s input and may be generated by SANE rather than typed by a person.</p><pre tabIndex={0}>{entry.authoredBody || "(Empty authored body)"}</pre></details>}
    <section><h3>Exact recorded outgoing text</h3><p className="muted">Original submission text, including any SANE framing. Read-only; nothing is resent.</p><pre tabIndex={0}>{entry.text}</pre></section>
    <button type="button" className="text-button" onClick={() => setAttempt(value => value + 1)}>Refresh recorded evidence</button>
  </>;
}

function ContextHistory({ sessionId }: { sessionId: string }) {
  const [state, setState] = useState<Load<ContextRun[]>>({ kind: "loading" });
  const [attempt, setAttempt] = useState(0);
  const [selected, setSelected] = useState("");
  const id = useId();
  useEffect(() => {
    let current = true;
    const controller = new AbortController(), signal = AbortSignal.any([controller.signal, AbortSignal.timeout(25_000)]);
    setState({ kind: "loading" });
    void loadContextRuns(sessionId, signal).then(value => { if (current) setState({ kind: "ready", value }); })
      .catch(error => { if (current) setState({ kind: "error", message: message(error) }); });
    return () => { current = false; controller.abort(); };
  }, [sessionId, attempt]);
  if (state.kind === "loading") return <p role="status">Loading recorded runs…</p>;
  if (state.kind === "error") return <div role="alert"><p className="notice error">{state.message}</p><button type="button" className="text-button" onClick={() => setAttempt(value => value + 1)}>Retry</button></div>;
  const run = state.value.find(item => item.id === selected) ?? state.value[0];
  if (!run) return <p role="status">No App-owned runs were recorded for this conversation. Imported history may not include SANE context evidence.</p>;
  return <>
    <label htmlFor={id}>Run</label>
    <select id={id} value={run.id} onChange={event => setSelected(event.target.value)}>{state.value.map(item => <option key={item.id} value={item.id}>{new Date(item.createdAt).toLocaleString()} · {item.id}</option>)}</select>
    <RunContext key={run.id} run={run} />
  </>;
}

/** No feature-owned payload cache, transcript projection, or local storage.
 * Payload reads start only while the explicit inspector is open. */
export function SaneContextDetails({ config, sessionId }: { config: Config; sessionId: string }) {
  const [opened, setOpened] = useState<Config | null>(null);
  return <section className="detail-section">
    <h3>SANE context</h3>
    <p className="muted">Inspect original recorded outgoing messages, including activation, updates and sharing when retained.</p>
    <button type="button" className="text-button" aria-haspopup="dialog" onClick={() => setOpened(config)}>View SANE context</button>
    {opened === config && <ShellDialog title="SANE context" subtitle={`Recorded outgoing evidence · ${sessionId}`} className="sane-context-dialog" close={() => setOpened(null)}>
      <div className="sane-context-inspection"><ContextHistory sessionId={sessionId} /></div>
    </ShellDialog>}
  </section>;
}
